"""Generates generated\\quarantine_plan.ps1 (reviewable, never auto-run) -
moves lower-quality duplicate copies (ranked by real resolution+source
quality via quality_score(), not just file size) into _Review Before
Delete for the user's own manual deletion - never auto-deleted."""
import json
import os
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
sys.path.insert(0, os.path.join(PROJECT_ROOT, "pipeline"))
from app_config import DATA_DIR, ARCHIVE_ROOT, QUEUE_PATH  # noqa: E402
DB_PATH = os.path.join(DATA_DIR, "media_db.json")
SCRIPT_OUT = os.path.join(PROJECT_ROOT, "generated", "quarantine_plan.ps1")

QUARANTINE_NAME = "_Review Before Delete"


def _under(path, root):
    if not root:
        return False
    root = os.path.normcase(os.path.abspath(root))
    path = os.path.normcase(os.path.abspath(path))
    return path == root or path.startswith(root + os.sep)


def quarantine_root_for(path):
    """Inside the incoming folder for queue files; next to the library root
    (outside it, so the scanner never sees it) for archived files."""
    if _under(path, QUEUE_PATH):
        return os.path.join(QUEUE_PATH, QUARANTINE_NAME)
    if _under(path, ARCHIVE_ROOT):
        return os.path.join(os.path.dirname(os.path.abspath(ARCHIVE_ROOT)), QUARANTINE_NAME)
    return None


def safe_folder_name(name):
    for ch in '<>:"/\\|?*':
        name = name.replace(ch, "_")
    return name.strip()


def main():
    with open(DB_PATH, encoding="utf-8") as f:
        shows = json.load(f)

    lines = [
        "# Duplicate quarantine plan - generated by build_quarantine_plan.py",
        "# Moves lower-quality duplicate copies into a '_Review Before Delete' folder.",
        "# NOTHING IS DELETED. Review the quarantine folders yourself and delete when ready.",
        "# Review this whole script before running it.",
        "",
        "$ErrorActionPreference = 'Stop'",
        "",
    ]

    total_items = 0
    total_bytes = 0
    per_show_summary = []

    for s in shows:
        if s["type"] == "Other":
            continue  # handled manually - not confidently identified
        if not s.get("duplicates"):
            continue
        show_bytes = sum(d["wasted_bytes"] for d in s["duplicates"])
        show_items = sum(len(d["extra_paths"]) for d in s["duplicates"])
        if show_items == 0:
            continue
        total_items += show_items
        total_bytes += show_bytes
        per_show_summary.append((s["title"], show_items, show_bytes))

        lines.append(f"# --- {s['title']} ({show_items} extra cop{'y' if show_items == 1 else 'ies'}, {show_bytes / 1e9:.1f} GB) ---")
        folder_name = safe_folder_name(s["title"])
        for dup in s["duplicates"]:
            for extra_path in dup["extra_paths"]:
                qroot = quarantine_root_for(extra_path)
                if not qroot:
                    continue
                dest_dir = os.path.join(qroot, folder_name)
                lines.append(f'New-Item -ItemType Directory -Force -Path "{dest_dir}" | Out-Null')
                lines.append(f'Move-Item -LiteralPath "{extra_path}" -Destination "{dest_dir}\\" -Force')
        lines.append("")

    with open(SCRIPT_OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    per_show_summary.sort(key=lambda x: x[2], reverse=True)
    print(f"Quarantine plan: {total_items} duplicate files, {total_bytes / 1e9:.1f} GB total.")
    print(f"Wrote {SCRIPT_OUT}")
    print("\nTop 15 shows by reclaimable space:")
    for title, items, b in per_show_summary[:15]:
        print(f"  - {title}: {items} extra cop{'y' if items == 1 else 'ies'}, {b / 1e9:.1f} GB")


if __name__ == "__main__":
    main()
